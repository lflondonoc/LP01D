public class OperadoresRelacionales {
    static void main() {
        //Ejericios con operadores de igualdad y relacionales
        boolean a= 4.8+5.0 >= 2*7;
        System.out.println(a);

        boolean b= 2%5 != Math.pow(3,2);
        System.out.println(b);

        boolean c= 9/4 <= 2+3;
        System.out.println(c);

        boolean d= 23-8 < 12/4+4;
        System.out.println(d);

        boolean e= 2*4+6 == 22/2+3;
        System.out.println(e);

    }
}
